"""Actual LingBot inference and evidence-backed furniture markers.

References (31 October 2026): see PLAN.md; upstream geometry.py and demo.py,
https://huggingface.co/docs/transformers/v5.8.0/model_doc/grounding-dino
https://trimesh.org/trimesh.points.html#trimesh.points.PointCloud
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time
import traceback
from state_io import update


def write_json(path, data):
    tmp = path.with_suffix('.tmp'); tmp.write_text(json.dumps(data)); tmp.replace(path)



def main(folder, repo):
    import numpy as np
    import torch
    import trimesh
    import cv2
    from PIL import Image
    sys.path.insert(0, str(repo))
    from lingbot_map.utils.geometry import unproject_depth_map_to_point_map

    state = json.loads((folder / 'state.json').read_text())
    video = Path(state['video'])
    capture=cv2.VideoCapture(str(video))
    source_fps=capture.get(cv2.CAP_PROP_FPS) or 30
    readable,first_frame=capture.read();capture.release()
    if not readable:raise ValueError('The video has no readable image frames.')
    portrait=first_frame.shape[0]>first_frame.shape[1]
    source_interval=max(1,round(source_fps/5))
    frame_times=[]
    try:
        metadata=json.loads(subprocess.check_output(['ffprobe','-v','error','-select_streams','v:0','-show_entries','frame=best_effort_timestamp_time','-of','json',str(video)],timeout=45))
        frame_times=[float(f['best_effort_timestamp_time']) if 'best_effort_timestamp_time' in f else None for f in metadata.get('frames',[])]
    except Exception:pass
    digest = hashlib.sha256(video.read_bytes()).hexdigest()
    if digest != state['source_sha256']:
        raise RuntimeError('Uploaded file changed before processing')
    update(folder, state='reconstructing', message='LingBot is estimating the room and camera path from your recording.')
    prediction_path = folder / 'predictions.pt'
    cmd = [str(repo / '.venv/bin/python'), str(repo / 'demo.py'),
           '--video_path', str(video), '--model_path', str(repo / 'models/lingbot-map.pt'),
           '--fps', '5', '--mode', 'windowed', '--window_size', '64',
           '--overlap_keyframes', '8', '--keyframe_interval', '2', '--use_sdpa',
           '--num_scale_frames', '2', '--camera_num_iterations', '4',
           '--save_predictions', str(prediction_path), '--no_viewer']
    if portrait: cmd.append('--rotate_clockwise_90')
    (folder / 'inference-command.json').write_text(json.dumps(cmd))
    subprocess.run(cmd, cwd=repo, check=True, timeout=650)
    # This file was generated by our own inference subprocess, never accepted as an upload.
    payload = torch.load(prediction_path, map_location='cpu', weights_only=False)
    pred = payload['predictions']

    def array(value):
        return value.detach().float().cpu().numpy() if isinstance(value, torch.Tensor) else np.asarray(value)

    depth, extrinsic, intrinsic = [array(pred[k]) for k in ('depth', 'extrinsic', 'intrinsic')]
    confidence = array(pred['depth_conf'])
    images = array(payload['images'])
    if depth.ndim == 5: depth = depth[0]
    if extrinsic.ndim == 4: extrinsic = extrinsic[0]
    if intrinsic.ndim == 4: intrinsic = intrinsic[0]
    if confidence.ndim == 4 and confidence.shape[0] == 1: confidence = confidence[0]
    if confidence.ndim == 4: confidence = confidence[..., 0]
    if images.ndim == 5: images = images[0]
    if images.shape[1] == 3: images = images.transpose(0, 2, 3, 1)
    if images.max() <= 1.01: images = images * 255
    images = np.clip(images, 0, 255).astype(np.uint8)
    count = len(images)
    frame_reference=[{'sample_index':i,'source_frame':i*source_interval,'time_seconds':frame_times[i*source_interval] if i*source_interval<len(frame_times) else None} for i in range(count)]
    write_json(folder/'frame-reference.json',frame_reference)
    if count < 3: raise ValueError('The video needs more frames. Try a longer recording.')
    first_camera = np.eye(4); first_camera[:3] = extrinsic[0][:3]
    # Undo the portrait preprocessing rotation, and convert camera down/forward to viewer up/back.
    basis = np.array([[0,1,0],[1,0,0],[0,0,-1]]) if portrait else np.diag([1,-1,-1])
    transform = np.eye(4); transform[:3,:3] = basis
    transform = transform @ first_camera
    write_json(folder / 'display-transform.json', transform.tolist())
    sampled = set(np.linspace(0, count-1, min(18,count), dtype=int).tolist())
    frame_maps = {}; all_points = []; all_colors = []
    for i in range(count):
        world = unproject_depth_map_to_point_map(depth[i:i+1], extrinsic[i:i+1], intrinsic[i:i+1])[0]
        world = (world @ transform[:3,:3].T + transform[:3,3]).astype(np.float32)
        conf = confidence[i]; rgb = images[i]
        dep = depth[i].squeeze()
        finite = np.isfinite(world).all(-1) & np.isfinite(conf) & np.isfinite(dep) & (dep > 0)
        cutoff = float(np.percentile(conf[finite], 50)) if finite.any() else float('inf')
        valid = finite & (conf >= cutoff)
        stride = max(2, int(np.ceil(np.sqrt(count * rgb.shape[0] * rgb.shape[1] / 900000))))
        mask = valid[::stride,::stride]
        all_points.append(world[::stride,::stride][mask]); all_colors.append(rgb[::stride,::stride][mask])
        if i in sampled:
            if portrait:
                rgb, world, valid = [np.rot90(a, 1).copy() for a in (rgb,world,valid)]
            frame_maps[i] = (rgb, world, valid)
    points = np.concatenate(all_points); colors = np.concatenate(all_colors)
    if len(points) < 1000: raise ValueError('Too little stable geometry was found. Try a slower walk with more overlap.')
    # Exclude only extreme isolated estimates; leave unknown surfaces visibly open.
    lo, hi = np.percentile(points,[.3,99.7],axis=0)
    keep = ((points >= lo) & (points <= hi)).all(1); points,colors=points[keep],colors[keep]
    extent = float(np.linalg.norm(np.ptp(points,axis=0)))
    objects=[]; note='Furniture detection was switched off.'
    update(folder, frames=count, point_count=len(points))
    if state.get('detect'):
        update(folder,state='detecting',message='Looking for chairs, tables and other furniture in sampled views.')
        try:
            from transformers import AutoProcessor, AutoModelForZeroShotObjectDetection
            model_id='IDEA-Research/grounding-dino-tiny'
            processor=AutoProcessor.from_pretrained(model_id)
            detector=AutoModelForZeroShotObjectDetection.from_pretrained(model_id).to('cuda').eval()
            names=['chair','table','desk','bed','wardrobe','cabinet','sofa']
            groups=[]; raw=[]; evidence_dir=folder/'evidence';evidence_dir.mkdir(exist_ok=True)
            for frame_index,(rgb,world,valid) in frame_maps.items():
                pic=Image.fromarray(rgb);width,height=pic.size
                inputs=processor(images=pic,text='. '.join(names)+'.',return_tensors='pt').to('cuda')
                with torch.no_grad(): outputs=detector(**inputs)
                result=processor.post_process_grounded_object_detection(outputs,inputs.input_ids,threshold=.30,text_threshold=.25,target_sizes=[(height,width)])[0]
                labels=result.get('text_labels',result.get('labels',[]))
                filename=f'frame-{frame_index}.jpg';pic.save(evidence_dir/filename,quality=90)
                for box,score,label in zip(result['boxes'].cpu().numpy(),result['scores'].cpu().numpy(),labels):
                    label=str(label).lower(); category=next((n for n in names if n in label),None)
                    if not category:continue
                    x1,y1,x2,y2=box
                    x1,x2=np.clip([x1,x2],0,width);y1,y2=np.clip([y1,y2],0,height)
                    if x2-x1<8 or y2-y1<8:continue
                    # Central box region reduces background contamination; it is not a segmentation mask.
                    xa,xb=int(x1+(x2-x1)*.2),int(x2-(x2-x1)*.2)
                    ya,yb=int(y1+(y2-y1)*.2),int(y2-(y2-y1)*.2)
                    region=world[ya:yb,xa:xb][valid[ya:yb,xa:xb]]
                    if len(region)<30:continue
                    center=np.median(region,axis=0)
                    spread=float(np.linalg.norm(np.percentile(region,75,axis=0)-np.percentile(region,25,axis=0)))
                    evidence={'file':filename,'box':[float(x1/width),float(y1/height),float(x2/width),float(y2/height)],**frame_reference[frame_index]}
                    record={'category':category,'confidence':float(score),'position':center.tolist(),'evidence':evidence,'spread':spread}
                    raw.append(record)
                    matches=[(np.linalg.norm(center-np.median(g['centers'],axis=0)),j) for j,g in enumerate(groups) if g['category']==category and frame_index not in g['frames']]
                    matches.sort()
                    radius=min(extent*.085,max(extent*.025,spread*.55))
                    if matches and matches[0][0]<radius:
                        j=matches[0][1];g=groups[j]
                        g['centers'].append(center);g['frames'].add(frame_index)
                        if score>g['best']['confidence']:g['best']=record
                    else:
                        groups.append({'category':category,'centers':[center],'frames':{frame_index},'best':record})
                update(folder,message=f'Checking furniture: {list(frame_maps).index(frame_index)+1} of {len(frame_maps)} views.')
            totals={}
            for group in sorted(groups,key=lambda g:-len(g['frames'])):
                # Require repeated evidence; single-view guesses remain in the private diagnostic record.
                if len(group['frames'])<2:continue
                category=group['category'];totals[category]=totals.get(category,0)+1
                best=group['best'];objects.append({'id':f'{category}-{totals[category]}','name':f'{category.capitalize()} {totals[category]}',
                    'category':category,'position':np.median(group['centers'],axis=0).tolist(),'confidence':best['confidence'],
                    'views':len(group['frames']),'evidence':best['evidence']})
            write_json(folder/'detection-observations.json',raw)
            note='Approximate locations from repeated image detections and estimated depth. Labels may be wrong; inspect the source image.' if objects else 'No furniture had enough repeated evidence for a reliable marker in this recording.'
            del detector;torch.cuda.empty_cache()
        except Exception:
            (folder/'detection-error.txt').write_text(traceback.format_exc())
            note='The room was reconstructed, but furniture detection could not finish for this run.'
            print(traceback.format_exc(),flush=True)
    update(folder,state='exporting',message='Preparing the interactive model and its source evidence.')
    cloud=trimesh.points.PointCloud(points,colors=colors)
    trimesh.Scene(cloud).export(str(folder/'model.glb'))
    cloud.export(str(folder/'model.ply'))
    result={'method':'LingBot-Map','representation':'colored point cloud','source_sha256':digest,'frames':count,'point_count':len(points),
            'portrait_rotation':portrait,'display_transform':transform.tolist(),'objects':objects,'detection_note':note,
            'model_sha256':hashlib.sha256((folder/'model.glb').read_bytes()).hexdigest()}
    write_json(folder/'result.json',result)
    update(folder,state='complete',frames=count,point_count=len(points),detection_note=note,message='Your room is ready. Drag to explore it, or select a furniture marker.')


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--job',type=Path,required=True);parser.add_argument('--repo',type=Path,required=True);args=parser.parse_args()
    try:main(args.job,args.repo)
    except Exception:
        (args.job/'runner-error.txt').write_text(traceback.format_exc());print(traceback.format_exc(),flush=True)
        update(args.job,state='failed',message='This recording could not be reconstructed. Try a shorter, steadier walk through the room.')
        sys.exit(1)
